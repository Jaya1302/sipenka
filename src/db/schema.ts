import {
  doublePrecision,
  jsonb,
  pgTable,
  serial,
  text,
  timestamp,
} from 'drizzle-orm/pg-core';
import type {
  Form10Data,
  Form12Data,
  Form13Data,
  Form1Data,
  Form2Data,
  Form3Data,
  Form4Data,
  Form5Data,
  Form6Data,
  Form7Data,
  Form8Data,
  Form9Data,
} from '../types/supervision.ts';

export const users = pgTable('users', {
  id: serial('id').primaryKey(),
  uid: text('uid').notNull().unique(),
  username: text('username').notNull().default(''),
  email: text('email').notNull(),
  displayName: text('display_name').notNull(),
  role: text('role').notNull().default('guru'),
  nip: text('nip').notNull().default(''),
  mataPelajaran: text('mata_pelajaran').notNull().default(''),
  konsentrasiKeahlian: text('konsentrasi_keahlian').notNull().default(''),
  photoURL: text('photo_url').notNull().default(''),
  createdAt: timestamp('created_at').defaultNow().notNull(),
  updatedAt: timestamp('updated_at').defaultNow().notNull(),
});

export const supervisions = pgTable('supervisions', {
  id: text('id').primaryKey(),
  createdByUid: text('created_by_uid').notNull(),
  teacherUid: text('teacher_uid').notNull().default(''),
  teacherUsername: text('teacher_username').notNull().default(''),
  teacherEmail: text('teacher_email').notNull().default(''),
  teacherName: text('teacher_name').notNull(),
  teacherNip: text('teacher_nip').notNull().default(''),
  mataPelajaran: text('mata_pelajaran').notNull(),
  konsentrasiKeahlian: text('konsentrasi_keahlian').notNull().default(''),
  kelasSemester: text('kelas_semester').notNull().default(''),
  tanggal: text('tanggal').notNull().default(''),
  tahap: text('tahap').notNull().default('PLAN'),
  status: text('status').notNull().default('draft'),
  totalNilai: doublePrecision('total_nilai').notNull().default(0),
  kategori: text('kategori').notNull().default('Perlu Perbaikan'),
  form1: jsonb('form1').$type<Form1Data>().notNull(),
  form2: jsonb('form2').$type<Form2Data>().notNull(),
  form3: jsonb('form3').$type<Form3Data>().notNull(),
  form4: jsonb('form4').$type<Form4Data>().notNull(),
  form5: jsonb('form5').$type<Form5Data>().notNull(),
  form6: jsonb('form6').$type<Form6Data>().notNull(),
  form7: jsonb('form7').$type<Form7Data>().notNull(),
  form8: jsonb('form8').$type<Form8Data>().notNull(),
  form9: jsonb('form9').$type<Form9Data>().notNull(),
  form10: jsonb('form10').$type<Form10Data>().notNull(),
  form12: jsonb('form12').$type<Form12Data>().notNull(),
  form13: jsonb('form13').$type<Form13Data>().notNull(),
  createdAt: timestamp('created_at').defaultNow().notNull(),
  updatedAt: timestamp('updated_at').defaultNow().notNull(),
});
